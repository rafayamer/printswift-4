const assert = require('node:assert/strict');
global.window = {};
require('../invoice-template.js');
const render = window.PrintSwiftInvoice.render;
const order = {id:'PS-1',customer:'Test',unit:'piece',qty:2,rateCents:500,totalCents:1000,paidCents:200,discountCents:0};
const a4 = render(order,'a4');
const receipt = render(order,'receipt80');
assert.ok(a4.includes('Rs 10.00'));
assert.ok(a4.includes('Rs 8.00'));
assert.ok(a4.includes('NOT FBR VERIFIED'));
assert.ok(receipt.includes('size:80mm auto'));
assert.ok(render({...order,customer:'<b>Jane</b>'},'a4').includes('&lt;b&gt;Jane&lt;/b&gt;'));
assert.ok(render({...order,id:'<b>1</b>'},'a4').includes('&lt;b&gt;1&lt;/b&gt;'));
assert.throws(()=>render({...order,paidCents:2000}));
assert.throws(()=>render({...order,qty:0}));
assert.throws(()=>render({...order,rateCents:-1}));
assert.throws(()=>render({...order,totalCents:1.5}));
assert.throws(()=>render({...order,unit:'bad'}));
assert.throws(()=>render({...order,due:'invalid-date'}));
assert.throws(()=>render(order,'receipt58'));
console.log('Invoice regression checks passed: 13 assertions');
